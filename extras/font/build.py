EXTRAS = Path(__file__).resolve().parent.parent
SOURCE = EXTRAS / "font" / "PlusJakartaSans-SemiBold-latin.woff2"
IMDB_SVG = EXTRAS / "logos" / "IMDb_PrimaryLogo_Gold.svg"
OUTPUT = EXTRAS / "silo-rating-logos.css"

# Source names are ASCII; anything else falls back to Silo's copy of the face.
UNICODES = range(0x20, 0x7F)
# Silo's tracking-tight, baked into the advances: browsers drop ligatures under letter-spacing.
TRACKING_EM = -0.025
# TMDB's logo height: 10px beside 13px title-page marks, 8px beside 12px small ones (ss01).
HEIGHTS = {"": 10 / 13, ".sm": 8 / 12}

# Letterboxd's decal (extras/logos/letterboxd-decal-dots-pos-rgb.svg), dots group coordinates.

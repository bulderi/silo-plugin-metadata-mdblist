def draw_glyph(draws, box, height_em, upem, centre_y):
    """Draw SVG shapes into a glyph height_em tall, centred on centre_y."""
    x, y, w, h = box
    scale = height_em * upem / h
    y_min = centre_y - height_em * upem / 2
    # SVG is y-down: flip, then move the box's corner to (0, y_min).
    matrix = (scale, 0, 0, -scale, -x * scale, y_min + (y + h) * scale)
    pen = TTGlyphPen(None)
    for draw in draws:
        draw(TransformPen(Cu2QuPen(pen, 1.0, reverse_direction=True), matrix))
    return pen.glyph(), round(w * scale)


def add_gsub_features(font, fea):
    """Add fea's lookups and features to the font's GSUB, keeping Jakarta's own."""
    scratch = TTFont()
    scratch.setGlyphOrder(font.getGlyphOrder())
    addOpenTypeFeaturesFromString(scratch, fea, tables=["GSUB"])
    gsub, extra = font["GSUB"].table, scratch["GSUB"].table
    # Appended, so Jakarta's lookups (and their nested indices) keep their place.
    shift = len(gsub.LookupList.Lookup)
    gsub.LookupList.Lookup.extend(extra.LookupList.Lookup)
    # The appended lookups' own nested indices, such as MC_USERS calling MC, move with them.
    tables = [subtable for lookup in extra.LookupList.Lookup for subtable in lookup.SubTable]
    while tables:
        table = tables.pop()
        if isinstance(table, otTables.SubstLookupRecord):
            table.LookupListIndex += shift
        tables.extend(entry.value for entry in table.iterSubTables())
    scripts = [record.Script for record in gsub.ScriptList.ScriptRecord]
    langsys = [s.DefaultLangSys for s in scripts if s.DefaultLangSys]
    langsys += [record.LangSys for s in scripts for record in s.LangSysRecord]
    records = gsub.FeatureList.FeatureRecord
    for new in extra.FeatureList.FeatureRecord:
        lookups = [i + shift for i in new.Feature.LookupListIndex]
        existing = [r for r in records if r.FeatureTag == new.FeatureTag]
        for record in existing:
            record.Feature.LookupListIndex.extend(lookups)
        if not existing:
            new.Feature.LookupListIndex = lookups
            records.append(new)
            for ls in langsys:
                ls.FeatureIndex.append(len(records) - 1)
    # The spec wants feature records sorted by tag.
    order = sorted(range(len(records)), key=lambda i: records[i].FeatureTag)
    position = {old: new for new, old in enumerate(order)}
    gsub.FeatureList.FeatureRecord = [records[i] for i in order]
    for ls in langsys:
        ls.FeatureIndex = sorted(position[i] for i in ls.FeatureIndex)
        ls.FeatureCount = len(ls.FeatureIndex)
    # fontTools' subsetter reads these counts rather than the lists' lengths.
    gsub.LookupList.LookupCount = len(gsub.LookupList.Lookup)
    gsub.FeatureList.FeatureCount = len(gsub.FeatureList.FeatureRecord)
    for record in gsub.FeatureList.FeatureRecord:
        record.Feature.LookupCount = len(record.Feature.LookupListIndex)


def build_font():
    font = TTFont(SOURCE, recalcTimestamp=False)
    glyf, hmtx = font["glyf"], font["hmtx"]
    upem = font["head"].unitsPerEm
    os2 = font["OS/2"]
    # Middle of the content area: where flex centring puts a mark's middle, as TMDB's logo.
    centre_y = (os2.sTypoAscender + os2.sTypoDescender) / 2
    tracking = round(TRACKING_EM * upem)
    for name in font.getGlyphOrder():
        advance, lsb = hmtx[name]
        if advance:
            hmtx[name] = (max(0, advance + tracking), lsb)

    palette, colr, ligatures, small = [], {}, [], []
    cmap = font.getBestCmap()

    def glyphs(text):
        return " ".join(cmap[ord(c)] for c in text)

    for key, (word, box, layers, fallback) in logos().items():
        heights = ICON_HEIGHTS if box[2] / box[3] <= ICON_MAX_ASPECT else HEIGHTS
        for suffix, height_em in heights.items():
            base = f"logo.{key}{suffix}"
            colr[base] = []
            for i, (rgb, draw) in enumerate(layers):
                if rgb not in palette:
                    palette.append(rgb)
                layer = f"{base}.l{i}"
                glyf[layer], _ = draw_glyph([draw], box, height_em, upem, centre_y)
                colr[base].append((layer, palette.index(rgb)))
            # The base glyph holds the fallback layers, for renderers without COLR.
            glyf[base], advance = draw_glyph([layers[i][1] for i in fallback], box, height_em, upem, centre_y)
            for name in [base] + [layer for layer, _ in colr[base]]:
                glyf[name].recalcBounds(glyf)
                hmtx[name] = (advance, getattr(glyf[name], "xMin", 0))
        ligatures.append(f"sub {glyphs(word)} by logo.{key};")
        small.append(f"sub logo.{key} by logo.{key}.sm;")

    font["COLR"] = buildCOLR(colr, version=0)
    font["CPAL"] = buildCPAL([[(r / 255, g / 255, b / 255, 1.0) for r, g, b in palette]])
    # rlig survives where browsers drop liga; Jakarta's calt only touches x and - after digits.
    # "RT Audience" needs no rule of its own: the RT ligature draws its start as RT's logo.
    # "MC Users" draws as Metacritic's logo then "Users": M C becomes the logo only before " Users".
    add_gsub_features(font, f"""
languagesystem DFLT dflt;
languagesystem latn dflt;
lookup LOGOS {{ {" ".join(ligatures)} }} LOGOS;
lookup MC {{ sub {glyphs("MC")} by logo.metacritic; }} MC;
lookup MC_USERS {{ sub {cmap[ord("M")]}' lookup MC {cmap[ord("C")]}' {glyphs(" Users")}; }} MC_USERS;
lookup SMALL {{ {" ".join(small)} }} SMALL;
feature liga {{ lookup LOGOS; lookup MC_USERS; }} liga;
feature rlig {{ lookup LOGOS; lookup MC_USERS; }} rlig;
feature ss01 {{ lookup SMALL; }} ss01;
""")

    names = font["name"]
    for name_id in (1, 3, 4, 6, 16, 17):
        names.removeNames(nameID=name_id)
    names.setName("Silo Rating Logos", 1, 3, 1, 0x409)
    names.setName("Silo Rating Logos SemiBold", 3, 3, 1, 0x409)
    names.setName("Silo Rating Logos SemiBold", 4, 3, 1, 0x409)
    names.setName("SiloRatingLogos-SemiBold", 6, 3, 1, 0x409)
    names.setName("This Font Software is licensed under the SIL Open Font License, Version 1.1. "
                  "The rating logos are their owners' trademarks.", 13, 3, 1, 0x409)

    options = Options()
    # What browsers apply by default, plus ss01; marks never ask for fractions or figure styles.
    options.layout_features = ["calt", "ccmp", "kern", "liga", "locl", "rlig", "ss01"]
    options.name_IDs = ["*"]
    options.hinting = False
    subsetter = Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)
    font.flavor = "woff2"
    return font


def main():
    woff2 = io.BytesIO()
    build_font().save(woff2)
    OUTPUT.write_text(CSS.replace("FONT_DATA", base64.b64encode(woff2.getvalue()).decode()))


if __name__ == "__main__":
    main()
